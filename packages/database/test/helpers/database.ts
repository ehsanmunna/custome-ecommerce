import { spawnSync } from 'node:child_process';
import {
  appendFileSync,
  cpSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import pg from 'pg';

const { Client } = pg;

export const packageRoot = process.cwd();
export const migrationUrl = process.env.MIGRATION_DATABASE_URL;
export const runtimeUrl = process.env.DATABASE_URL;
export const hasDatabase = Boolean(migrationUrl && runtimeUrl);

const RESET_SQL = `
DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public AUTHORIZATION current_user;
GRANT USAGE ON SCHEMA public TO app_runtime;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO app_runtime;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO app_runtime;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
`;

export interface MigrationFixture {
  name: string;
  sql: string;
}

export interface FixtureProject {
  migrationsDir: string;
  schemaPath: string;
  cleanup: () => void;
}

export async function withClient<T>(
  connectionString: string,
  callback: (client: pg.Client) => Promise<T>,
): Promise<T> {
  const client = new Client({ connectionString });
  await client.connect();
  try {
    return await callback(client);
  } finally {
    await client.end();
  }
}

export async function resetDatabase(): Promise<void> {
  if (!migrationUrl) {
    throw new Error('MIGRATION_DATABASE_URL is required for database integration tests');
  }
  await withClient(migrationUrl, async (client) => {
    await client.query(RESET_SQL);
  });
}

function prismaBinary(): string {
  const binary = process.platform === 'win32' ? 'prisma.cmd' : 'prisma';
  return resolve(packageRoot, 'node_modules', '.bin', binary);
}

export function runMigrateCommand(extraEnv: Record<string, string> = {}): {
  status: number | null;
  stdout: string;
  stderr: string;
} {
  const result = spawnSync(process.execPath, [resolve(packageRoot, 'scripts', 'migrate.mjs')], {
    cwd: packageRoot,
    env: { ...process.env, ...extraEnv },
    encoding: 'utf8',
  });
  return { status: result.status, stdout: result.stdout, stderr: result.stderr };
}

export function deployFixtureProject(project: FixtureProject): {
  status: number | null;
  stdout: string;
  stderr: string;
} {
  const result = spawnSync(prismaBinary(), ['migrate', 'deploy', '--schema', project.schemaPath], {
    cwd: packageRoot,
    env: { ...process.env, DATABASE_URL: migrationUrl },
    encoding: 'utf8',
    shell: process.platform === 'win32',
  });

  return { status: result.status, stdout: result.stdout, stderr: result.stderr };
}

export function createFixtureProject(fixtures: MigrationFixture[]): FixtureProject {
  const root = mkdtempSync(join(tmpdir(), 'ecommerce-schema-'));
  const migrationsDir = join(root, 'migrations');
  mkdirSync(migrationsDir, { recursive: true });

  const committedMigrations = resolve(packageRoot, 'prisma', 'migrations');
  for (const entry of readdirSync(committedMigrations, { withFileTypes: true })) {
    if (entry.isDirectory() && /^\d{14}_.+$/.test(entry.name)) {
      cpSync(join(committedMigrations, entry.name), join(migrationsDir, entry.name), {
        recursive: true,
      });
    }
  }

  writeFileSync(
    join(migrationsDir, 'migration_lock.toml'),
    '# Please do not edit this file manually\nprovider = "postgresql"\n',
    'utf8',
  );

  const schemaPath = join(root, 'schema.prisma');
  writeFileSync(
    schemaPath,
    `generator client {\n  provider = "prisma-client-js"\n}\n\ndatasource db {\n  provider = "postgresql"\n  url      = env("DATABASE_URL")\n}\n`,
    'utf8',
  );

  const project: FixtureProject = {
    migrationsDir,
    schemaPath,
    cleanup: () => rmSync(root, { recursive: true, force: true }),
  };

  for (const fixture of fixtures) {
    addFixtureMigration(project, fixture);
  }

  return project;
}

export function addFixtureMigration(project: FixtureProject, fixture: MigrationFixture): void {
  const directory = join(project.migrationsDir, fixture.name);
  mkdirSync(directory, { recursive: true });
  writeFileSync(join(directory, 'migration.sql'), `${fixture.sql.trim()}\n`, 'utf8');
}

export function editFixtureMigration(project: FixtureProject, name: string, suffix: string): void {
  appendFileSync(join(project.migrationsDir, name, 'migration.sql'), `\n${suffix}\n`, 'utf8');
}

export async function readSchemaVersion(): Promise<string | null> {
  if (!migrationUrl) {
    throw new Error('MIGRATION_DATABASE_URL is required for database integration tests');
  }
  return withClient(migrationUrl, async (client) => {
    try {
      const result = await client.query('SELECT version FROM schema_version LIMIT 1');
      return (result.rows[0]?.version as string | undefined) ?? null;
    } catch (error) {
      if ((error as { code?: string }).code === '42P01') {
        return null;
      }
      throw error;
    }
  });
}

export async function readLedger(): Promise<
  Array<{ migration_name: string; checksum: string; finished_at: Date | null }>
> {
  if (!migrationUrl) {
    throw new Error('MIGRATION_DATABASE_URL is required for database integration tests');
  }
  return withClient(migrationUrl, async (client) => {
    const result = await client.query(
      'SELECT migration_name, checksum, finished_at FROM _prisma_migrations ORDER BY migration_name',
    );
    return result.rows;
  });
}

export async function insertProbeRow(value: string): Promise<void> {
  if (!runtimeUrl) {
    throw new Error('DATABASE_URL is required for database integration tests');
  }
  await withClient(runtimeUrl, async (client) => {
    await client.query('INSERT INTO probe (id, name) VALUES (1, $1)', [value]);
  });
}

export async function readProbeRow(): Promise<{ id: number; name: string } | undefined> {
  if (!runtimeUrl) {
    throw new Error('DATABASE_URL is required for database integration tests');
  }
  return withClient(runtimeUrl, async (client) => {
    const result = await client.query('SELECT id, name FROM probe WHERE id = 1');
    return result.rows[0];
  });
}
