import { readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { packageRoot } from './env.mjs';

const migrationsDir = resolve(packageRoot, 'prisma', 'migrations');
const versions = readdirSync(migrationsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && /^\d{14}_.+$/.test(entry.name))
  .map((entry) => entry.name)
  .sort();

if (versions.length === 0) {
  console.error(
    'No migrations found. Add a migration before generating the expected schema version.',
  );
  process.exit(1);
}

const latest = versions[versions.length - 1];
const target = resolve(packageRoot, 'src', 'expected-version.ts');
const contents = `// Generated by scripts/generate-expected-version.mjs. Do not edit by hand.\nexport const EXPECTED_SCHEMA_VERSION = '${latest}';\n`;

writeFileSync(target, contents, 'utf8');
console.log(`Expected schema version: ${latest}`);
